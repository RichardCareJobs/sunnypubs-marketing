const POSTS_DIR = path.join(ROOT, 'blog', 'posts');
const BLOG_DIR = path.join(ROOT, 'blog');
const SITE = 'https://sunnypubs.app';
const GENERATED_MARK = '<!-- generated by scripts/build-blog.js — edit blog/posts/*.md instead -->';

// The blog is not public yet. Flip to false at launch: pages stop carrying
// <meta name="robots" content="noindex"> and blog URLs are added to sitemap.xml.
const NOINDEX = true;

// Preferred city order for the filter pills; cities found in posts but not
// listed here are appended alphabetically, so new cities Just Work.
const CITY_ORDER = ['Dublin', 'Cork', 'London', 'Birmingham', 'Manchester'];

const render = require(path.join(BLOG_DIR, 'blog-render.js'));
