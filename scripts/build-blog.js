/* ── Sitemap (only once the blog is public) ───────────────────── */

function updateSitemap(posts) {
  const file = path.join(ROOT, 'sitemap.xml');
  let xml = fs.readFileSync(file, 'utf8');
  // Drop any existing /blog/ entries, then re-append fresh ones.
  xml = xml.replace(/\s*<url>\s*<loc>https:\/\/sunnypubs\.app\/blog\/[\s\S]*?<\/url>/g, '');
  const entries = [`  <url>
    <loc>${SITE}/blog/</loc>
    <changefreq>weekly</changefreq>
    <priority>0.7</priority>
  </url>`].concat(posts.map((p) => `  <url>
    <loc>${SITE}/blog/${p.slug}/</loc>
    <changefreq>monthly</changefreq>
    <priority>0.5</priority>
  </url>`));
  xml = xml.replace('</urlset>', entries.join('\n') + '\n</urlset>');
  fs.writeFileSync(file, xml);
  console.log('sitemap.xml updated with blog URLs');
}

/* ── Main ─────────────────────────────────────────────────────── */

function main() {
  const posts = loadPosts();
  if (!posts.length) throw new Error('no posts found in blog/posts/');
  const cities = cityList(posts);

  // Remove previously generated post directories whose source .md is gone.
  const slugs = new Set(posts.map((p) => p.slug));
  for (const entry of fs.readdirSync(BLOG_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name === 'posts') continue;
    const idx = path.join(BLOG_DIR, entry.name, 'index.html');
    if (fs.existsSync(idx) && fs.readFileSync(idx, 'utf8').includes(GENERATED_MARK) && !slugs.has(entry.name)) {
      fs.rmSync(path.join(BLOG_DIR, entry.name), { recursive: true });
      console.log(`removed stale blog/${entry.name}/`);
    }
  }

  fs.writeFileSync(path.join(BLOG_DIR, 'index.html'), listingPage(posts, cities));
  console.log('built blog/index.html');

  for (const post of posts) {
    const dir = path.join(BLOG_DIR, post.slug);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'index.html'), postPage(post, posts, cities));
    console.log(`built blog/${post.slug}/index.html`);
  }

  if (!NOINDEX) updateSitemap(posts);
  console.log(`\n${posts.length} posts · cities: ${cities.join(', ')}${NOINDEX ? '\nNOINDEX is on — pages carry a noindex tag and sitemap.xml is untouched.' : ''}`);
}

main();
