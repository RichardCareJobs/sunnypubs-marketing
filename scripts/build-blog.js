/* ── Front matter ─────────────────────────────────────────────── */

function parseFrontMatter(raw, file) {
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!m) throw new Error(`${file}: missing front matter (--- block at top)`);
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const kv = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
    if (!kv) throw new Error(`${file}: bad front matter line: "${line}"`);
    let v = kv[2].trim().replace(/^["'](.*)["']$/, '$1');
    meta[kv[1]] = v;
  }
  return { meta, body: raw.slice(m[0].length) };
}

/* ── Markdown (subset) → post body blocks ─────────────────────────
   Supported:  ## subhead · > pull quote · - bullet list ·
               :::tip … ::: Sunny tip box · paragraphs ·
               **bold** *italic* [link](url)
   The first paragraph becomes the lead. */

function inline(s) {
  return esc(s)
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/\*([^*]+)\*/g, '<em>$1</em>')
    .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, '<a href="$2">$1</a>');
}

function markdownToBlocks(md, file) {
  const blocks = [];
  const lines = md.split(/\r?\n/);
  let i = 0, sawLead = false;
  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim()) { i++; continue; }

    if (line.startsWith(':::tip')) {
      const buf = [];
      i++;
      while (i < lines.length && !lines[i].startsWith(':::')) { buf.push(lines[i]); i++; }
      if (i >= lines.length) throw new Error(`${file}: unclosed :::tip block`);
      i++; // closing :::
      blocks.push({ k: 'tip', t: buf.join(' ').trim() });
      continue;
    }
    if (line.startsWith('## ')) {
      blocks.push({ k: 'h', t: line.slice(3).trim() });
      i++; continue;
    }
    if (line.startsWith('> ')) {
      const buf = [];
      while (i < lines.length && lines[i].startsWith('> ')) { buf.push(lines[i].slice(2)); i++; }
      blocks.push({ k: 'quote', t: buf.join(' ').trim() });
      continue;
    }
    if (/^[-*] /.test(line)) {
      const items = [];
      while (i < lines.length && /^[-*] /.test(lines[i])) { items.push(lines[i].slice(2).trim()); i++; }
      blocks.push({ k: 'list', items });
      continue;
    }
    // paragraph: consume until blank line
    const buf = [];
    while (i < lines.length && lines[i].trim() && !/^(## |> |[-*] |:::)/.test(lines[i])) {
      buf.push(lines[i].trim()); i++;
    }
    blocks.push({ k: sawLead ? 'p' : 'lead', t: buf.join(' ') });
    sawLead = true;
  }
  return blocks;
}

function blocksHtml(blocks) {
  return blocks.map((b) => {
    if (b.k === 'lead') return `<p class="post-lead">${inline(b.t)}</p>`;
    if (b.k === 'p') return `<p class="post-p">${inline(b.t)}</p>`;
    if (b.k === 'h') return `<h2 class="post-h">${inline(b.t)}</h2>`;
    if (b.k === 'quote') return `<blockquote class="post-quote"><p>${inline(b.t)}</p></blockquote>`;
    if (b.k === 'list') {
      return `<ul class="post-list">${b.items.map((it) => `<li><span class="dot" aria-hidden="true"></span><span>${inline(it)}</span></li>`).join('')}</ul>`;
    }
    if (b.k === 'tip') {
      return `<div class="post-tip"><img src="/assets/sunny_icon.png" alt="" aria-hidden="true"><div><div class="post-tip-label">Sunny tip</div><p>${inline(b.t)}</p></div></div>`;
    }
    return '';
  }).join('\n');
}

function wordCount(blocks) {
  let n = 0;
  for (const b of blocks) {
    if (b.t) n += b.t.split(/\s+/).length;
    if (b.items) for (const it of b.items) n += it.split(/\s+/).length;
  }
  return n;
}

/* ── Load posts ───────────────────────────────────────────────── */

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

function displayDate(iso, file) {
  const m = iso.match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!m) throw new Error(`${file}: date must be YYYY-MM-DD (got "${iso}")`);
  return `${Number(m[3])} ${MONTHS[Number(m[2]) - 1]} ${m[1]}`;
}

function loadPosts() {
  if (!fs.existsSync(POSTS_DIR)) throw new Error('blog/posts/ not found');
  const posts = [];
  for (const f of fs.readdirSync(POSTS_DIR).sort()) {
    if (!f.endsWith('.md') || f.toLowerCase() === 'readme.md') continue;
    const file = `blog/posts/${f}`;
    const raw = fs.readFileSync(path.join(POSTS_DIR, f), 'utf8');
    const { meta, body } = parseFrontMatter(raw, file);
    if (meta.draft === 'true') continue;

    for (const req of ['title', 'excerpt', 'category', 'city', 'author', 'date']) {
      if (!meta[req]) throw new Error(`${file}: front matter is missing "${req}"`);
    }
    if (!render.CATEGORY[meta.category]) {
      throw new Error(`${file}: category must be one of ${Object.keys(render.CATEGORY).join(' | ')}`);
    }

    const slug = (meta.slug || f.replace(/\.md$/, '')).toLowerCase()
      .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
    const blocks = markdownToBlocks(body, file);
    const image = meta.image
      ? { type: 'photo', src: meta.image }
      : { type: 'grad', grad: meta.gradient || 'sunset' };

    posts.push({
      slug,
      title: meta.title,
      excerpt: meta.excerpt,
      category: meta.category,
      city: meta.city,
      author: meta.author,
      isoDate: meta.date,
      date: displayDate(meta.date, file),
      read: meta.read || `${Math.max(2, Math.round(wordCount(blocks) / 200))} min`,
      featured: meta.featured === 'true',
      image,
      blocks
    });
  }
  posts.sort((a, b) => (a.isoDate < b.isoDate ? 1 : a.isoDate > b.isoDate ? -1 : 0));
  const seen = new Set();
  for (const p of posts) {
    if (seen.has(p.slug)) throw new Error(`duplicate slug "${p.slug}"`);
    seen.add(p.slug);
  }
  return posts;
}

function cityList(posts) {
  const found = new Set(posts.map((p) => p.city));
  const ordered = CITY_ORDER.filter((c) => found.has(c));
  const extra = [...found].filter((c) => !CITY_ORDER.includes(c)).sort();
  return ordered.concat(extra);
}

