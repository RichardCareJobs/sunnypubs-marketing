/* Sunny blog builder.
   Reads Markdown posts from blog/posts/*.md and generates:
     - blog/index.html            (listing page: featured story + grid + city filter)
     - blog/<slug>/index.html     (one page per post)
   When NOINDEX is false it also refreshes the /blog/ entries in sitemap.xml.

   Zero dependencies — run with:  node scripts/build-blog.js
   See blog/posts/README.md for the authoring format. */

'use strict';

